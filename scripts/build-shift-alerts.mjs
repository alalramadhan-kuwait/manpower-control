// Bundles the edge functions that run the app's engine (src/core, src/data): supabase/functions/<name>/main.ts into
// index.ts, the file that is deployed (shift-alerts, sd-plan-approve). Run: npm run functions:build. A test rebuilds them
// and fails when a committed index.ts is stale.
import { build } from 'esbuild';
import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const FUNCTIONS = ['shift-alerts', 'sd-plan-approve'];
const dirOf = (name) => resolve(root, 'supabase/functions', name);
const dir = dirOf('shift-alerts');
export const OUT = resolve(dir, 'index.ts');
export const outOf = (name) => resolve(dirOf(name), 'index.ts');

/** The data layer imports the browser client; on the server it gets the service-key client instead. */
const serverClient = (fdir) => ({
  name: 'server-client',
  setup(b) {
    b.onResolve({ filter: /(^|\/)supabase$/ }, (a) => (a.importer.includes('/src/data/') ? { path: resolve(fdir, 'supabase-shim.ts') } : undefined));
  }
});

export async function bundle(name = 'shift-alerts') {
  const fdir = dirOf(name);
  const r = await build({
    entryPoints: [resolve(fdir, 'main.ts')], bundle: true, write: false, format: 'esm', platform: 'neutral', target: 'es2022',
    alias: { '@': resolve(root, 'src') }, external: ['npm:*'], plugins: [serverClient(fdir)], legalComments: 'none', charset: 'utf8', logLevel: 'error'
  });
  return `// GENERATED by scripts/build-shift-alerts.mjs from main.ts and the app's src/core and src/data: do not edit; run npm run functions:build.\n${r.outputFiles[0].text}`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  for (const name of FUNCTIONS) {
    const text = await bundle(name);
    writeFileSync(outOf(name), text);
    console.log(`${name}/index.ts: ${text.length} bytes`);
  }
}
