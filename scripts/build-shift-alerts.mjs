// Bundles supabase/functions/shift-alerts/main.ts with the app's engine (src/core, src/data) into index.ts, the file
// that is deployed. Run: npm run functions:build. A test rebuilds it and fails when the committed index.ts is stale.
import { build } from 'esbuild';
import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const dir = resolve(root, 'supabase/functions/shift-alerts');
export const OUT = resolve(dir, 'index.ts');

/** The data layer imports the browser client; on the server it gets the service-key client instead. */
const serverClient = {
  name: 'server-client',
  setup(b) {
    b.onResolve({ filter: /(^|\/)supabase$/ }, (a) => (a.importer.includes('/src/data/') ? { path: resolve(dir, 'supabase-shim.ts') } : undefined));
  }
};

export async function bundle() {
  const r = await build({
    entryPoints: [resolve(dir, 'main.ts')], bundle: true, write: false, format: 'esm', platform: 'neutral', target: 'es2022',
    alias: { '@': resolve(root, 'src') }, external: ['npm:*'], plugins: [serverClient], legalComments: 'none', charset: 'utf8', logLevel: 'error'
  });
  return `// GENERATED by scripts/build-shift-alerts.mjs from main.ts and the app's src/core and src/data: do not edit; run npm run functions:build.\n${r.outputFiles[0].text}`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = await bundle();
  writeFileSync(OUT, text);
  console.log(`shift-alerts/index.ts: ${text.length} bytes`);
}
