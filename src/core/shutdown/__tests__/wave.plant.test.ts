const H = 3_600_000;
const T0 = { oct: Date.UTC(2026, 9, 28, 3), jan: Date.UTC(2026, 0, 23, 15) };
const readings = (rows: Row[], t0: number, upTo: number): WaveReading[] => rows.filter((r) => r[0]! <= upTo && r[2] != null).map((r) => ({
  at: t0 + r[0]! * H, pts: { r105_in: r[1]!, r105_out: r[2]!, r101_in: r[3]!, r102_in: r[4]!, r103_in: r[5]!, r104_in: r[6]!, r104_out: r[7]!, e129_feed: r[8]!, e129_out: r[9]! }, beds: {} }));
const first = (rows: Row[], col: number, v: number) => rows.find((r) => r[col]! >= v)![0]!;
const of = (e: NonNullable<ReturnType<typeof cutinEstimate>>, k: string) => e.reactors.find((r) => r.key === k)!;

describe('one train, fresh catalyst (Oct-26)', () => {
  const spec: CutinSpec = { ...TRAIN1_CUTIN, catalyst: 'fresh' };
  it('E-129 takes ~28% of (R-105 outlet − feed in), and R-101 cannot reach 600 with R-105 inlet at 620', () => {
    const e = cutinEstimate(readings(OCT, T0.oct, 20), spec)!;
    expect(e.e129!.eff!).toBeGreaterThan(0.24); expect(e.e129!.eff!).toBeLessThan(0.32);
    expect(of(e, 'r101').wont).toBe(true); expect(of(e, 'r101').max!).toBeLessThan(595);
    expect(e.exo.now).toBe(0);
  });
  it('from 02:00 on 29 Oct: R-103 and R-104 there within 2 h of when they were; R-102 tops out where it sat with the inlet at 620', () => {
    const e = cutinEstimate(readings(OCT, T0.oct, 20), spec)!;
    for (const [k, col] of [['r103', 5], ['r104', 6]] as const) {
      const want = T0.oct + first(OCT, col, spec.targets[k]) * H;
      expect(of(e, k).eta).not.toBeNull(); expect(Math.abs(of(e, k).eta! - want) / H).toBeLessThan(2);
    }
    // 05:00, inlet 621 for 4 h: R-102 at 574.7; it passed 580 only after the inlet was raised past 620
    expect(Math.abs(of(e, 'r102').max! - OCT[23][4]!)).toBeLessThan(3);
  });
  it('raising the R-105 inlet to 634 (as the plant did) lets R-101 near 600', () => {
    const e = cutinEstimate(readings(OCT, T0.oct, 20), { ...spec, inletMax: 634 })!;
    expect(of(e, 'r101').max!).toBeGreaterThan(of(cutinEstimate(readings(OCT, T0.oct, 20), spec)!, 'r101').max! + 8);
  });
});

describe('two trains, used catalyst (Jan-26)', () => {
  const spec: CutinSpec = { ...TRAIN1_CUTIN, catalyst: 'used', r101Hold: 610 };
  it('the feed into E-129 runs ~75 °F hotter than with one train', () => {
    expect(JAN[47][8]! - OCT[26][8]!).toBeGreaterThan(60);
  });
  it('with used catalyst it expects the exotherm and finds every inlet there within 3 h of when it was', () => {
    const e = cutinEstimate(readings(JAN, T0.jan, 42), spec)!;
    expect(e.exo.expected).toBe(true); expect(e.blocked).toBe(false);
    const want = T0.jan + Math.max(...([3, 4, 5, 6] as const).map((c, i) => first(JAN, c, [600, 580, 570, 560][i]))) * H;
    expect(e.ready).not.toBeNull(); expect(Math.abs(e.ready! - want) / H).toBeLessThan(3);
  });
  it('taken as fresh catalyst, the same readings say R-101 will not make it: the catalyst decides', () => {
    const e = cutinEstimate(readings(JAN, T0.jan, 42), { ...spec, catalyst: 'fresh' })!;
    expect(of(e, 'r101').wont).toBe(true);
  });
  it('R-101 inlet held at 610 by TC-172', () => {
    const e = cutinEstimate(readings(JAN, T0.jan, 46), spec)!;
    expect(of(e, 'r101').max!).toBeLessThanOrEqual(610); expect(e.exo.now).toBeGreaterThan(20);
  });
});

